import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { build } from "esbuild";
const result = await build({
  entryPoints: ["src/components/math/surface-entry.js"],
  bundle: true,
  conditions: ["browser", "development"],
  plugins: [
    {
      name: "inline-mathlive-assets",
      setup(build) {
        build.onLoad({ filter: /mathlive\.mjs$/ }, (args) => {
          const source = readFileSync(args.path, "utf8");
          // Assets are embedded, so inline scripts need no script-URL inference.
          const anchor = "|| getFileUrl();";
          if (!source.includes(anchor)) throw new Error("Review MathLive inline asset initialization after upgrading.");
          return { contents: source.replace(anchor, "|| document.baseURI;"), loader: "js" };
        });
      },
    },
  ],
  write: false,
  minify: true,
  format: "iife",
  target: "es2020",
});
const css = readFileSync("node_modules/mathlive/mathlive-static.css", "utf8").replace(
  /url\(([^)]+)\)/g,
  (_, path) => `url(data:font/woff2;base64,${readFileSync("node_modules/mathlive/" + path).toString("base64")})`,
);
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; font-src data:; img-src data:; connect-src 'none'"><style>${css}body{margin:0;padding:8px;font-family:system-ui;color:#172136;background:transparent;overflow-x:auto}math-field{display:block;min-height:60px;font-size:24px;border-radius:12px}#keyboard{position:relative;min-height:0}canvas{display:block;background:#fff;border:1px solid #a7b8d7;border-radius:12px;touch-action:none;width:100%;height:280px}button{padding:10px;margin:3px;border:1px solid #a7b8d7;border-radius:8px;background:#f5f7fb;color:#172136}#render{white-space:pre-wrap;overflow-wrap:anywhere;line-height:1.7}.block{display:block;overflow-x:auto}#status{font-size:13px}</style></head><body><div id="root"></div><script>${result.outputFiles[0].text.replaceAll("</script", "<\\/script")}</script></body></html>`;
mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/math-surface.ts",
  "// Generated by npm run math:build.\nexport const MATH_SURFACE_HTML = " + JSON.stringify(html) + ";\n",
);

writeFileSync("src/generated/math-static.ts", "// Generated by math:build.\nexport const MATH_STATIC_CSS = " + JSON.stringify(css) + ";\n");
